const {chromium}=require('playwright');
const assert=require('node:assert/strict');
const fs=require('node:fs/promises');
const path=require('node:path');
const base=(process.env.QUEST_BASE_URL||'http://127.0.0.1:4173').replace(/\/$/,'');
const key='ai-product-quest-v1';
(async()=>{
  const browser=await chromium.launch({headless:true,...(process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE?{executablePath:process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE}:{})});
  const context=await browser.newContext({viewport:{width:1440,height:1000}});
  const page=await context.newPage(),errors=[];
  page.on('pageerror',e=>errors.push(e.message));
  await page.goto(base+'/');
  await page.evaluate(k=>localStorage.setItem(k,JSON.stringify({version:1,read:['methods'],passed:['methods'],notes:{methods:'旧版真实学习笔记'},quests:{},runs:{}})),key);
  await page.goto(base+'/#path');await page.reload();
  const state=()=>page.evaluate(k=>JSON.parse(localStorage.getItem(k)),key);
  await page.locator('#growth-pace').selectOption('4');
  assert.equal((await state()).notes.methods,'旧版真实学习笔记');
  assert.equal((await state()).passed.length,1);
  assert((await page.locator('main').innerText()).includes('第 23—24 周'));
  await page.locator('[data-growth="week"][data-id="6"]').click();
  await page.reload();assert.equal((await state()).learning.week,6);
  await page.locator('#growth-pace').selectOption('8');
  await page.screenshot({path:path.join(__dirname,'qa-artifacts','growth-path-desktop.png'),fullPage:true});
  await page.goto(base+'/#unit/versions');
  await page.locator('[data-growth="save"]').click();
  assert.equal((await state()).learning.units.versions?.savedAt,undefined);
  await page.locator('[data-growth-field="prediction"]').fill('我预测最新上传的版本不一定适用于历史时点，需要根据有效期和对象来筛选。');
  await page.locator('[data-growth-field="explain"]').fill('有效版本必须结合查询日期、适用对象和权限判断，上传时间不能代替生效时间。');
  await page.locator('[data-growth-field="transfer"]').fill('供应商证书需要核对去年有效期，最新续期证书不能自动证明历史资质。');
  await page.locator('[data-growth-mode]').selectOption('independent');
  await page.locator('[data-growth="save"]').click();
  let s=await state();assert(s.learning.units.versions.savedAt);assert.equal(s.learning.reviews.versions.stage,0);
  assert(Date.parse(s.learning.reviews.versions.due)>Date.now());
  const originalDue=s.learning.reviews.versions.due;
  await page.locator('[data-growth="save"]').click();assert.equal((await state()).learning.reviews.versions.due,originalDue);
  await page.goto(base+'/#review');
  await page.locator('[data-growth-field="answer"]').fill('历史查询需要当时有效的资料，而不是只取上传最新的规范。这是我的提前复测回答。');
  await page.locator('[data-result="ready"]').click();
  assert.equal((await state()).learning.reviews.versions.stage,0,'early practice must not advance');
  await page.evaluate(k=>{const s=JSON.parse(localStorage.getItem(k));s.learning.reviews.versions.due=new Date(Date.now()-60000).toISOString();localStorage.setItem(k,JSON.stringify(s));},key);
  await page.reload();await page.locator('[data-result="ready"]').click();
  s=await state();assert.equal(s.learning.reviews.versions.stage,1);assert.equal(s.learning.reviews.versions.history.length,1);
  const days=(Date.parse(s.learning.reviews.versions.due)-Date.now())/86400000;assert(days>5.9&&days<6.1);
  await page.locator('[data-growth-field="answer"]').fill('还需要补充历史时点查询的依据，不能独立解释权限和有效版本的关系。');
  await page.locator('[data-result="again"]').click();s=await state();assert.equal(s.learning.reviews.versions.stage,1);assert.equal(s.learning.reviews.versions.history.length,2);
  assert(Date.parse(s.learning.reviews.versions.due)<Date.now()+86401000);
  await page.goto(base+'/#practice/rag-detective');
  await page.locator('#g-valid').check();await page.locator('[data-growth="search"]').click();
  await page.waitForFunction(()=>document.getElementById('g-results').textContent.includes('候选'));
  assert(!(await page.locator('#g-results').innerText()).includes('photo-old'));
  assert((await page.locator('#g-results').innerText()).includes('photo-new'));
  await page.locator('#g-at').fill('2026-08-15');await page.locator('[data-growth="search"]').click();
  await page.waitForFunction(()=>document.getElementById('g-results').textContent.includes('2026-08-15'));
  assert(!(await page.locator('#g-results').innerText()).includes('photo-new'));
  assert((await page.locator('#g-results').innerText()).includes('photo-old'));
  for(const field of ['prediction','result','limits'])await page.locator('[data-growth-field="'+field+'"]').fill('合成实验记录：比较有效期过滤前后的候选证据，保留历史时点查询和无答案边界。<img src=x onerror="window.bad=1">');
  await page.locator('[data-growth="save"]').click();assert((await state()).learning.labs['rag-detective'].savedAt);
  await page.reload();assert.equal(await page.evaluate(()=>window.bad),undefined);
  await page.screenshot({path:path.join(__dirname,'qa-artifacts','growth-lab-desktop.png'),fullPage:true});
  const zip=await page.request.get(base+'/materials/ai-quest-learning-kit.zip');assert.equal(zip.status(),200);assert.equal((await zip.body()).subarray(0,2).toString(),'PK');
  const ids=await page.evaluate(()=>Object.keys(window.QUEST_CURRICULUM.units));assert.equal(ids.length,18);
  for(const id of ids){await page.goto(base+'/#unit/'+id);assert.equal(await page.locator('[data-growth-field="explain"]').count(),1);assert.equal(await page.locator('.growth-reading').count(),1);}
  await page.goto(base+'/#project');
  for(const id of ['P0','P1']){
    for(const field of ['evidence','decision'])await page.locator('[data-kind="project"][data-id="'+id+'"][data-growth-field="'+field+'"]').fill('这是本人对合成工单任务的决策记录，明确规则基线、数据来源以及尚未验证的限制。');
    await page.locator('[data-growth="save"][data-id="'+id+'"]').click();
    assert((await page.locator('#g-save-project-'+id).innerText()).includes('已提交'));
  }
  await page.goto(base+'/#journal');const download=page.waitForEvent('download');await page.locator('#export-top').click();
  const backup=path.join(__dirname,'qa-artifacts','growth-backup.json');await (await download).saveAs(backup);
  const exported=JSON.parse(await fs.readFile(backup,'utf8'));assert.equal(exported.notes.methods,'旧版真实学习笔记');assert.equal(exported.learning.reviews.versions.history.length,2);
  const fresh=await browser.newContext();const restored=await fresh.newPage();await restored.goto(base+'/#journal');await restored.locator('#import-file').setInputFiles(backup);
  await restored.waitForFunction(k=>JSON.parse(localStorage.getItem(k)).learning.reviews.versions.history.length===2,key);
  await restored.goto(base+'/#unit/versions');assert((await restored.locator('[data-growth-field="explain"]').inputValue()).includes('有效版本必须'));
  await restored.locator('[data-growth-field="explain"]').fill('我在新浏览器中的更新笔记，导入同名旧备份时应该保留当前内容。');
  await restored.goto(base+'/#journal');await restored.locator('#import-file').setInputFiles(backup);await restored.waitForTimeout(150);
  assert((await restored.evaluate(k=>JSON.parse(localStorage.getItem(k)).learning.units.versions.explain,key)).includes('新浏览器'));
  const phone=await browser.newContext({viewport:{width:390,height:844},isMobile:true,hasTouch:true});const mobile=await phone.newPage();mobile.on('pageerror',e=>errors.push(e.message));
  for(const route of ['map','path','unit/versions','practice','practice/rag-detective','project','review','bridge']){
    await mobile.goto(base+'/#'+route);assert.equal(await mobile.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1),true,'overflow: '+route);
    if(route==='path')await mobile.screenshot({path:path.join(__dirname,'qa-artifacts','growth-path-mobile.png'),fullPage:true});
  }
  assert.deepEqual(errors,[]);
  await browser.close();console.log('PASS: legacy migration, 18 deep units, schedules, early/failed recall, actual retrieval, kit download, project evidence, export/import, and 8 mobile routes.');
})().catch(e=>{console.error(e);process.exit(1);});
